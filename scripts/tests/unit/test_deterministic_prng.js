import { generatePuzzle, countSolutions, createPRNG } from '../../../src/engine/SudokuEngine.js';
import { getDailyPuzzle } from '../../../src/utils/dailyChallenge.js';

console.log('====================================================');
console.log('🧪 DETERMINISTIC PRNG & DAILY CHALLENGE QA SUITE');
console.log('====================================================\n');

let passedTests = 0;
let totalTests = 0;

function assert(condition, message) {
  totalTests++;
  if (!condition) {
    console.error(`❌ [FAIL] ${message}`);
    process.exit(1);
  } else {
    console.log(`  ✅ [PASS] ${message}`);
    passedTests++;
  }
}

// 1. PRNG Generator Consistency
console.log('▶ Test 1: PRNG Number Sequence Reproducibility');
const prng1 = createPRNG('test-seed-123');
const seq1 = Array.from({ length: 5 }, () => prng1());
const prng2 = createPRNG('test-seed-123');
const seq2 = Array.from({ length: 5 }, () => prng2());
assert(JSON.stringify(seq1) === JSON.stringify(seq2), 'Identical seeds produce identical float sequences');

// 2. 100x Deterministic Puzzle Generation
console.log('\n▶ Test 2: 100x Repetitive Puzzle Generation on 2026-08-29');
const baseDaily = getDailyPuzzle('2026-08-29');
const baseBoardStr = JSON.stringify(baseDaily.board);
const baseSolStr = JSON.stringify(baseDaily.solution);

let allMatches = true;
for (let i = 0; i < 100; i++) {
  const trial = getDailyPuzzle('2026-08-29');
  if (JSON.stringify(trial.board) !== baseBoardStr || JSON.stringify(trial.solution) !== baseSolStr) {
    allMatches = false;
    break;
  }
}
assert(allMatches, '100/100 Trials generated byte-for-byte identical board & solution');

// 3. Unique Solution Verification across all 5 difficulty levels with seed
console.log('\n▶ Test 3: Unique Solution Guarantees for Seeded Levels 1~5');
for (let lvl = 1; lvl <= 5; lvl++) {
  const seeded = generatePuzzle(lvl, `level-seed-${lvl}-2026`);
  const solutions = countSolutions(seeded.board, 2);
  assert(solutions === 1, `Level ${lvl} seeded puzzle has exactly 1 unique solution`);
}

// 4. Date-to-Date Puzzle Uniqueness
console.log('\n▶ Test 4: Different Dates Produce Distinct Puzzles');
const day1 = getDailyPuzzle('2026-08-29');
const day2 = getDailyPuzzle('2026-08-30');
const day3 = getDailyPuzzle('2026-09-01');
assert(JSON.stringify(day1.board) !== JSON.stringify(day2.board), '2026-08-29 vs 2026-08-30 produces distinct puzzles');
assert(JSON.stringify(day2.board) !== JSON.stringify(day3.board), '2026-08-30 vs 2026-09-01 produces distinct puzzles');

// 5. The killer daily (2026-10-21, KP-4). One calendar for both kinds (user
// 2026-10-07: "통합"): the daily screen's switch picks the kind, and a killer day
// must be one killer for every player, exactly as the standard day is.
console.log('\n▶ Test 5: The Killer Daily — Same Date, Same Killer, For Everyone');
const k1 = getDailyPuzzle('2026-08-29', 'killer');
let killerSame = true;
for (let i = 0; i < 5; i++) {
  const t = getDailyPuzzle('2026-08-29', 'killer');
  if (['board', 'solution', 'cages'].some((f) => JSON.stringify(t[f]) !== JSON.stringify(k1[f]))) { killerSame = false; break; }
}
assert(k1.variant === 'killer' && Array.isArray(k1.cages) && k1.cages.length > 0, 'The killer daily is a killer, with its cages');
assert(killerSame, '5/5 killer dailies for one date are identical — board, solution and cages');
assert(k1.level === baseDaily.level && k1.dateKey === '2026-08-29' && k1.isDaily === true,
  'The killer daily has that day\'s level, date and daily flag — the mission sets the level for both kinds');
assert(JSON.stringify(k1.cages) !== JSON.stringify(getDailyPuzzle('2026-08-30', 'killer').cages), 'Different dates produce distinct killer dailies');
assert(baseDaily.variant !== 'killer' && !baseDaily.cages, 'The standard daily is still a standard puzzle');

console.log('\n----------------------------------------------------');
console.log(`🎉 ALL ${passedTests}/${totalTests} PRNG & DAILY CHALLENGE TESTS PASSED!`);
console.log('----------------------------------------------------');
